using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace DocMe.HideIslands
{
    /// <summary>Tracks which model file a generated mesh was built from, and turns stored picks back into vertices.</summary>
    public static class SourceModel
    {
        /// <summary>Where every DocMe tool writes its generated meshes. Nothing in here is ever a source model.</summary>
        public const string GenRoot = "Assets/DocMe Generated";
        public const string GenDir = GenRoot + "/Meshes";

        public static bool IsGenerated(string assetPath) => !string.IsNullOrEmpty(assetPath) && assetPath.StartsWith(GenRoot + "/");

        public static void EnsureGenDir()
        {
            if (AssetDatabase.IsValidFolder(GenDir)) return;
            Directory.CreateDirectory(Path.Combine(Directory.GetCurrentDirectory(), GenDir));
            AssetDatabase.Refresh();
        }

        /// <summary>The model file a mesh ultimately comes from. A mesh generated by any DocMe tool inherits
        /// the source that tool recorded.</summary>
        public static void Root(GameObject avatar, Mesh mesh, out string path, out string meshName)
        {
            path = mesh != null ? AssetDatabase.GetAssetPath(mesh) : null;
            meshName = mesh != null ? mesh.name : null;
            if (!IsGenerated(path)) return;
            foreach (var h in DocMeReapply.Handlers)
                if (h.TryGetSource(avatar, mesh, out var p, out var n) && !string.IsNullOrEmpty(p)) { path = p; meshName = n; return; }
        }

        public static string Hash(IEnumerable<string> paths)
        {
            var sb = new StringBuilder();
            foreach (var p in paths.Where(p => !string.IsNullOrEmpty(p) && !IsGenerated(p)).Distinct().OrderBy(p => p))
                sb.Append(p).Append(':').Append(AssetDatabase.GetAssetDependencyHash(p)).Append(';');
            return sb.ToString();
        }

        /// <summary>The source mesh by name, for when the stored reference went missing.</summary>
        public static Mesh Resolve(string path, string meshName, string rendererName)
        {
            if (string.IsNullOrEmpty(path) || IsGenerated(path)) return null;
            var meshes = AssetDatabase.LoadAllAssetsAtPath(path).OfType<Mesh>().ToList();
            return meshes.FirstOrDefault(m => m.name == meshName) ?? meshes.FirstOrDefault(m => m.name == rendererName);
        }

        public static DocMePick ToPick(GameObject avatar, string label, IslandPick pick)
        {
            Vector3 world = pick.point;
            if (world == default && pick.renderer != null)
            {
                var verts = MeshBake.BakeWorldVertices(pick.renderer, out var baked);
                Object.DestroyImmediate(baked);
                if (pick.vertex >= 0 && pick.vertex < verts.Length) world = verts[pick.vertex];
            }
            return new DocMePick { label = label, renderer = pick.renderer, avatarLocalPoint = avatar.transform.InverseTransformPoint(world) };
        }

        public class BakeCache
        {
            readonly Dictionary<SkinnedMeshRenderer, (Vector3[] world, int[] tris)> map = new Dictionary<SkinnedMeshRenderer, (Vector3[], int[])>();
            public (Vector3[] world, int[] tris) Get(SkinnedMeshRenderer r)
            {
                if (map.TryGetValue(r, out var v)) return v;
                var world = MeshBake.BakeWorldVertices(r, out var baked);
                Object.DestroyImmediate(baked);
                return map[r] = (world, r.sharedMesh.triangles);
            }
        }

        /// <summary>Resolves a stored pick to the triangle it was clicked on (closest surface, not closest
        /// vertex: a neighbouring island's vertex can be nearer than the clicked triangle's own corners).
        /// Fails if no surface is left near that spot.</summary>
        public static bool TryResolve(GameObject avatar, DocMePick pick, BakeCache cache, out IslandPick seed)
        {
            seed = default;
            var r = pick.renderer;
            if (r == null || r.sharedMesh == null || !r.sharedMesh.isReadable) return false;
            var (world, tris) = cache.Get(r);

            Vector3 target = avatar.transform.TransformPoint(pick.avatarLocalPoint);
            float tol = 0.004f * Mathf.Max(Mathf.Abs(avatar.transform.lossyScale.y), 1e-3f);
            float bestSq = tol * tol; int bestTri = -1;
            for (int t = 0; t < tris.Length; t += 3)
            {
                Vector3 a = world[tris[t]], b = world[tris[t + 1]], c = world[tris[t + 2]];
                if ((a - b).sqrMagnitude < 1e-14f && (a - c).sqrMagnitude < 1e-14f) continue; // folded away
                float d = (ClosestOnTriangle(target, a, b, c) - target).sqrMagnitude;
                if (d < bestSq) { bestSq = d; bestTri = t; }
            }
            if (bestTri < 0) return false;

            int best = tris[bestTri];
            for (int k = 1; k < 3; k++)
                if ((world[tris[bestTri + k]] - target).sqrMagnitude < (world[best] - target).sqrMagnitude) best = tris[bestTri + k];
            seed = new IslandPick { renderer = r, vertex = best, point = target };
            return true;
        }

        // Ericson, Real-Time Collision Detection 5.1.5
        static Vector3 ClosestOnTriangle(Vector3 p, Vector3 a, Vector3 b, Vector3 c)
        {
            Vector3 ab = b - a, ac = c - a, ap = p - a;
            float d1 = Vector3.Dot(ab, ap), d2 = Vector3.Dot(ac, ap);
            if (d1 <= 0f && d2 <= 0f) return a;
            Vector3 bp = p - b;
            float d3 = Vector3.Dot(ab, bp), d4 = Vector3.Dot(ac, bp);
            if (d3 >= 0f && d4 <= d3) return b;
            float vc = d1 * d4 - d3 * d2;
            if (vc <= 0f && d1 >= 0f && d3 <= 0f) return a + ab * (d1 / (d1 - d3));
            Vector3 cp = p - c;
            float d5 = Vector3.Dot(ab, cp), d6 = Vector3.Dot(ac, cp);
            if (d6 >= 0f && d5 <= d6) return c;
            float vb = d5 * d2 - d1 * d6;
            if (vb <= 0f && d2 >= 0f && d6 <= 0f) return a + ac * (d2 / (d2 - d6));
            float va = d3 * d6 - d5 * d4;
            if (va <= 0f && (d4 - d3) >= 0f && (d5 - d6) >= 0f) return b + (c - b) * ((d4 - d3) / ((d4 - d3) + (d5 - d6)));
            float denom = 1f / (va + vb + vc);
            return a + ab * (vb * denom) + ac * (vc * denom);
        }
    }
}
